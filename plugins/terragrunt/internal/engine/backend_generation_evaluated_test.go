const dynamicParent = `locals {
  environment = read_terragrunt_config("env.hcl")
}
remote_state {
  backend  = "local"
  config   = { path = "${get_terragrunt_dir()}/state/terraform.tfstate" }
  generate = { path = "backend.tf", if_exists = "overwrite" }
}
generate "context" {
  path              = "context.tf"
  if_exists         = "overwrite"
  disable_signature = true
  contents          = @CONTENTS@
}
`

// writeDynamicParent writes a parent configuration whose generate block interpolates a local, as the
// advanced fixture's root.hcl does, and returns a backend-phase request for a unit that includes it.
func writeDynamicParent(t *testing.T, contents string) model.Request {
	t.Helper()
	request := nativeUnit(t, "include \"root\" {\n  path = \"root.hcl\"\n}\ninputs = { value = run_cmd(\"must-not-evaluate-inputs\") }\n")
	request.Phase = phaseBackend
	directory := filepath.Dir(request.Path)
	require.NoError(t, os.WriteFile(filepath.Join(directory, "env.hcl"), []byte("locals {\n  region = \"us-east-2\"\n}\n"), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(directory, "root.hcl"), []byte(strings.Replace(dynamicParent, "@CONTENTS@", contents, 1)), 0o600))
	return request
}

// A state read of a unit whose included generate block interpolates locals evaluates that block in the
// read-only environment, proves it declares no backend, and returns the unit's remote_state identity.
func TestBackendPhaseAcceptsEvaluatedGenerateWithoutBackend(t *testing.T) {
	request := writeDynamicParent(t, `"output \"generated_region\" { value = \"${local.environment.locals.region}\" }\n"`)

	result, err := Resolve(t.Context(), request)

	require.NoError(t, err)
	assert.Equal(t, "local", result.BackendType)
	directory, err := filepath.EvalSymlinks(filepath.Dir(request.Path))
	require.NoError(t, err)
	assert.Equal(t, filepath.Join(directory, "state", "terraform.tfstate"), result.Backend["path"])
	assert.True(t, result.BackendGenerated)
}

// The evaluated check still rejects a block that generates a backend, one whose contents need a
// command, which the read-only state read never runs, and one that renders a file it cannot parse.
func TestBackendPhaseRejectsEvaluatedGenerateThatCannotBeVerified(t *testing.T) {
	for name, contents := range map[string]string{
		"backend":                  `"terraform {\n  backend \"local\" { path = \"${local.environment.locals.region}.tfstate\" }\n}\n"`,
		"command":                  `run_cmd("must-not-execute")`,
		"unparsable rendered file": `"not ${local.environment.locals.region} valid hcl {"`,
	} {
		t.Run(name, func(t *testing.T) {
			request := writeDynamicParent(t, contents)

			result, err := Resolve(t.Context(), request)

			require.ErrorIs(t, err, ErrUnsupportedExecution)
			require.ErrorContains(t, err, "Cannot verify the backend identity")
			require.NotContains(t, err.Error(), "must-not")
			require.Nil(t, result)
		})
	}
}

// A rendered Terraform file that does not parse, such as JSON with the Terragrunt signature line, cannot be
// proven free of a backend; a file Terraform does not load never declares one.
func TestProvablyWithoutBackend(t *testing.T) {
	for _, test := range []struct {
		path, content string
		want          bool
	}{
		{"notes.txt", "terraform { backend \"local\" {} }", true},
		{"vars.tf", "variable \"a\" {}\n", true},
		{"backend.tf", "terraform {\n  backend \"local\" {}\n}\n", false},
		{"broken.tf", "x", false},
		{"vars.tf.json", `{"variable":{"a":{}}}`, true},
		{"backend.tf.json", `{"terraform":{"backend":{"s3":{}}}}`, false},
		{"signed.tf.json", "# Generated by Terragrunt\n{\"terraform\":{\"backend\":{\"s3\":{}}}}", false},
		{"cloud.tofu", "terraform {\n  cloud {}\n}\n", false},
	} {
		assert.Equal(t, test.want, provablyWithoutBackend(test.path, []byte(test.content)), test.path)
	}
}

// A disabled declaration writes nothing, so it is not rendered, and an escaping target path fails closed.
func TestEvaluatedGenerationSkipsDisabledAndRejectsEscapingPaths(t *testing.T) {
	disabled := writeDynamicParent(t, "\"terraform {\\n  backend \\\"local\\\" {}\\n}\\n\"\n  disable = local.environment.locals.region == \"us-east-2\"")
	result, err := Resolve(t.Context(), disabled)
	require.NoError(t, err)
	assert.Equal(t, "local", result.BackendType)

	escaping := nativeUnit(t, "locals {\n  name = \"x\"\n}\ngenerate \"up\" {\n  path = \"../${local.name}.tf\"\n  if_exists = \"overwrite\"\n  contents = \"# x\"\n}\n")
	escaping.Phase = phaseBackend
	_, err = Resolve(t.Context(), escaping)
	require.ErrorContains(t, err, "Cannot verify the backend identity")
}
