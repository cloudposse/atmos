func TestGenerationUsesUpstreamFormattingAndOwnership(t *testing.T) {
	request := nativeUnit(t, `generate "provider" {
 path = "nested/provider.tf"
 if_exists = "overwrite_terragrunt"
 comment_prefix = "// "
 contents = "locals { enabled=true }"
}
generate "disabled" {
 path = "obsolete.tf"
 if_exists = "error"
 disable = true
 if_disabled = "remove_terragrunt"
 contents = "ignored"
}
generate "json" {
 path = "data.json"
 if_exists = "skip"
 disable_signature = true
 contents = "{\"a\":true}"
}`)
	result, err := Resolve(t.Context(), request)
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(result.Generated[filepath.Join("nested", "provider.tf")], "// Generated by Terragrunt. Sig: nIlQXj57tbuaRZEa\n"))
	require.Contains(t, result.Generated[filepath.Join("nested", "provider.tf")], "enabled = true")
	require.Equal(t, "overwrite_terragrunt", result.GeneratedPolicies[filepath.Join("nested", "provider.tf")])
	require.Equal(t, "remove_terragrunt", result.GeneratedPolicies["obsolete.tf"])
	require.Empty(t, result.Generated["obsolete.tf"])
	require.Equal(t, `{"a":true}`, result.Generated["data.json"])
	require.Equal(t, "skip", result.GeneratedPolicies["data.json"])
	require.NoDirExists(t, filepath.Join(filepath.Dir(request.Path), "nested"))
}

