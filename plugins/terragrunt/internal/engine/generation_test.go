func TestGenerationUsesUpstreamFormattingAndOwnership(t *testing.T) {
	request := nativeUnit(t, `generate "provider" {
 path = "nested/provider.tf"
 if_exists = "overwrite_terragrunt"
 comment_prefix = "// "
 contents = "locals { enabled=true }"
}
generate "disabled" {
 path = "obsolete.tf"
 if_exists = "error"
 disable = true
 if_disabled = "remove_terragrunt"
 contents = "ignored"
}
generate "json" {
 path = "data.json"
 if_exists = "skip"
 disable_signature = true
 contents = "{\"a\":true}"
}`)
	result, err := Resolve(t.Context(), request)
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(result.Generated[filepath.Join("nested", "provider.tf")], "// Generated by Terragrunt. Sig: nIlQXj57tbuaRZEa\n"))
	require.Contains(t, result.Generated[filepath.Join("nested", "provider.tf")], "enabled = true")
	require.Equal(t, "overwrite_terragrunt", result.GeneratedPolicies[filepath.Join("nested", "provider.tf")])
	require.Equal(t, "remove_terragrunt", result.GeneratedPolicies["obsolete.tf"])
	require.Empty(t, result.Generated["obsolete.tf"])
	require.Equal(t, `{"a":true}`, result.Generated["data.json"])
	require.Equal(t, "skip", result.GeneratedPolicies["data.json"])
	require.NoDirExists(t, filepath.Join(filepath.Dir(request.Path), "nested"))
}

func TestGenerationRejectsDuplicateTargetsAndDisabledEscape(t *testing.T) {
	for _, extra := range []string{`generate "a" {
 path = "same.tf"
 if_exists = "overwrite"
 contents = ""
}
generate "b" {
 path = "./same.tf"
 if_exists = "overwrite"
 contents = ""
}`, `generate "a" {
 path = "../escape.tf"
 if_exists = "overwrite"
 disable = true
 if_disabled = "remove"
 contents = ""
}`} {
		_, err := Resolve(t.Context(), nativeUnit(t, extra))
		require.Error(t, err)
	}
}

func TestRemoteModuleSourceRemainsUnfetched(t *testing.T) {
	request := nativeUnit(t, "")
	uri := "git::https://example.invalid/repository.git//module?ref=v1.2.3"
	require.NoError(t, os.WriteFile(request.Path, []byte("terraform { source = \""+uri+"\" }\n"), 0o600))
	for _, phase := range []string{"discover", "backend", ""} {
		request.Phase = phase
		result, err := Resolve(t.Context(), request)
		require.NoError(t, err)
		require.Equal(t, uri, result.Source)
		require.Empty(t, result.Folders)
		require.NoDirExists(t, filepath.Join(filepath.Dir(request.Path), ".terragrunt-cache"))
	}
}

func TestPreventDestroyUsesCommandAndBooleanArguments(t *testing.T) {
	for _, test := range []struct {
		command string
		args    []string
		blocked bool
	}{
		{"plan", nil, false},
		{"apply", nil, false},
		{"destroy", nil, true},
		{"plan", []string{"-destroy"}, true},
		{"apply", []string{"--destroy=true"}, true},
		{"apply", []string{"-destroy", "-destroy=false"}, false},
		{"apply", []string{"-destroy=false", "-destroy=1"}, true},
	} {
		t.Run(test.command+strings.Join(test.args, " "), func(t *testing.T) {
			request := nativeUnit(t, "prevent_destroy = true")
			request.Command, request.Arguments = test.command, test.args
			_, err := Resolve(t.Context(), request)
			if test.blocked {
				require.ErrorContains(t, err, "protected by prevent_destroy")
			} else {
				require.NoError(t, err)
			}
		})
	}
}

func TestPreventDestroyRejectsBeforeInputEffects(t *testing.T) {
	request := nativeUnit(t, `prevent_destroy = true
inputs = { value = run_cmd("must-not-execute") }`)
	request.Command = "destroy"
	_, err := Resolve(t.Context(), request)
	require.ErrorContains(t, err, "protected by prevent_destroy")
	require.NotContains(t, err.Error(), "must-not-execute")
}

func TestPreventDestroyGuardFailsClosedWhenConfigCannotBeParsed(t *testing.T) {
	request := nativeUnit(t, "inputs = {")
	request.Command = "destroy"
	result, err := Resolve(t.Context(), request)
	require.Error(t, err, "an unreadable unit must not proceed to a destroy")
	require.Nil(t, result)
	require.NotContains(t, err.Error(), "protected by prevent_destroy", "the failure is a parse error, not a protection verdict")
}
