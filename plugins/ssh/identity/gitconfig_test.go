package identity_test

import (
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"

	"github.com/cloudposse/atmos/plugins/ssh/identity"
)

func absolute(parts ...string) string {
	return filepath.Join(append([]string{string(filepath.Separator) + "srv"}, parts...)...)
}

func TestGitConfigIncludesTheUsersConfigurationFirst(t *testing.T) {
	g := identity.GitConfig{
		Includes:     []string{"/home/u/.gitconfig", "/home/u/.config/git/config"},
		Signing:      true,
		SSHKeygen:    "/usr/bin/ssh-keygen",
		SigningKey:   "ssh-ed25519 AAAAC3Nza",
		RewriteHTTPS: []string{"github.com", "git.example.com:8443"},
	}

	got := g.Render("ops")

	want := `# Generated by the Atmos SSH plugin for identity "ops". Edits are overwritten at the next login.
[include]
	path = "/home/u/.gitconfig"
	path = "/home/u/.config/git/config"
[gpg]
	format = ssh
[gpg "ssh"]
	program = "/usr/bin/ssh-keygen"
[user]
	signingkey = "key::ssh-ed25519 AAAAC3Nza"
[commit]
	gpgsign = true
[tag]
	gpgsign = true
[url "ssh://git@github.com/"]
	insteadOf = "https://github.com/"
[url "ssh://git@git.example.com:8443/"]
	insteadOf = "https://git.example.com:8443/"
`
	assert.Equal(t, want, got)
	include := strings.Index(got, "[include]")
	for _, section := range []string{"[gpg]", "[user]", "[commit]", "[tag]", "[url "} {
		assert.Less(t, include, strings.Index(got, section), "%s comes after the include", section)
	}
}

func TestGitConfigWithoutSigningOnlyRewritesURLs(t *testing.T) {
	g := identity.GitConfig{Includes: []string{"/h/.gitconfig"}, RewriteHTTPS: []string{"github.com"}}

	got := g.Render("ops")

	assert.Contains(t, got, "[url \"ssh://git@github.com/\"]")
	assert.NotContains(t, got, "gpgsign")
	assert.NotContains(t, got, "signingkey")
	assert.NotContains(t, got, "[gpg")
}

func TestGitConfigQuotesAwkwardValues(t *testing.T) {
	g := identity.GitConfig{
		Includes: []string{`/home/a "b"/.gitconfig`}, Signing: true, SSHKeygen: "/opt/ssh keygen/ssh-keygen",
		SigningKey: "ssh-ed25519 AAAA",
	}

	got := g.Render(`na"me`)

	assert.Contains(t, got, `identity "na\"me"`)
	assert.Contains(t, got, `path = "/home/a \"b\"/.gitconfig"`)
	assert.Contains(t, got, `program = "/opt/ssh keygen/ssh-keygen"`)
}

func TestGitConfigEscapesBackslashesThatAreNotSeparators(t *testing.T) {
	if filepath.Separator == '\\' {
		t.Skip("on Windows backslashes are separators and are written as slashes")
	}
	g := identity.GitConfig{Includes: []string{`/home/a\b/.gitconfig`}}

	assert.Contains(t, g.Render("ops"), `path = "/home/a\\b/.gitconfig"`)
}
