package identity

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/cloudposse/atmos/plugins/ssh/paths"
)

const gitDirName = "git"

// GitConfigPath returns the generated Git configuration file of identity.
func GitConfigPath(p *paths.Paths, identity string) (string, error) {
	if err := paths.ValidateIdentity(identity); err != nil {
		return "", err
	}
	return filepath.Join(p.Root(), gitDirName, identity+".gitconfig"), nil
}

// GitConfig describes the generated Git configuration.
type GitConfig struct {
	// Includes are the user's own configuration files, read first so this file overrides them.
	Includes []string
	// Signing turns on SSH commit and tag signing.
	Signing bool
	// SSHKeygen is the absolute path of ssh-keygen, for gpg.ssh.program.
	SSHKeygen string
	// SigningKey is the public key in authorized_keys form.
	SigningKey string
	// RewriteHTTPS lists hosts whose HTTPS URLs are rewritten to SSH.
	RewriteHTTPS []string
}

// Render returns the file content. The user's configuration is included before anything else
// is set, so the settings below win over it.
func (g GitConfig) Render(identity string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by the Atmos SSH plugin for identity %s. Edits are overwritten at the next login.\n", quote(identity))
	if len(g.Includes) > 0 {
		b.WriteString("[include]\n")
		for _, path := range g.Includes {
			fmt.Fprintf(&b, "\tpath = %s\n", quote(filepath.ToSlash(path)))
		}
	}
	if g.Signing {
		fmt.Fprintf(&b, "[gpg]\n\tformat = ssh\n")
		fmt.Fprintf(&b, "[gpg \"ssh\"]\n\tprogram = %s\n", quote(filepath.ToSlash(g.SSHKeygen)))
		fmt.Fprintf(&b, "[user]\n\tsigningkey = %s\n", quote("key::"+g.SigningKey))
		b.WriteString("[commit]\n\tgpgsign = true\n[tag]\n\tgpgsign = true\n")
	}
	for _, host := range g.RewriteHTTPS {
		fmt.Fprintf(&b, "[url %s]\n\tinsteadOf = %s\n", quote("ssh://git@"+host+"/"), quote("https://"+host+"/"))
	}
	return b.String()
}

// quote returns s as a double-quoted Git configuration value.
func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)
	return `"` + r.Replace(s) + `"`
}

// writeGitConfig writes the file for identity, or removes it when none is needed. It leaves an
// unchanged file alone.
func writeGitConfig(p *paths.Paths, identity string, g *GitConfig) (string, error) {
	path, err := GitConfigPath(p, identity)
	if err != nil {
		return "", err
	}
	if g == nil {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return "", fmt.Errorf("remove %s: %w", path, err)
		}
		return "", nil
	}
	want := []byte(g.Render(identity))
	if have, err := os.ReadFile(path); err == nil && string(have) == string(want) {
		return path, nil
	}
	if err := writeAtomic(path, want); err != nil {
		return "", err
	}
	return path, nil
}
