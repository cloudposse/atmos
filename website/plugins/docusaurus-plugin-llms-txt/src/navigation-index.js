const fs = require('node:fs/promises');
const path = require('node:path');

const routeKey = (route) => route.replace(/\/$/, '') || '/';
const labelText = (text) => String(text).replace(/[\r\n]+/g, ' ').replace(/[\\[\]]/g, '\\$&');
const readable = (name) => ({cli: 'CLI', howto: 'How-to Guides', cheatsheets: 'Cheat Sheets'}[name] || name.replace(/[-_]/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()));
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-|-$/g, '').slice(0, 64) || 'section';
const markdownURL = (route) => `${routeKey(route) === '/' ? '/index' : routeKey(route)}.md`;
const link = (node) => `[${labelText(node.title)}](<${node.url}>)`;
const count = (node) => `${node.pages.size} page${node.pages.size === 1 ? '' : 's'}`;

/** Build navigation from Docusaurus's resolved sidebars, including autogenerated items. */
async function generateNavigationIndexes(documents, versions, outDir, siteConfig) {
  const byRoute = new Map(documents.map((doc) => [routeKey(doc.routePath), doc]));
  const visited = new Set();
  const generated = new Map();
  const base = (siteConfig.baseUrl || '/').replace(/\/$/, '');
  const rootURL = `${base}/index.md`;
  const navbarLabels = new Map();
  const navbarOrder = [];
  function collectLabels(items = []) {
    for (const item of items) {
      if (item.label) navbarOrder.push(item.label);
      if (item.sidebarId && item.label) navbarLabels.set(item.sidebarId, item.label);
      collectLabels(item.items);
    }
  }
  collectLabels(siteConfig.themeConfig?.navbar?.items);

  function page(route, title) {
    const doc = byRoute.get(routeKey(route));
    if (!doc) return null;
    visited.add(routeKey(doc.routePath));
    return { title: title || doc.title, url: markdownURL(doc.routePath), pages: new Set([routeKey(doc.routePath)]) };
  }

  function category(title, children, landing, key) {
    const pages = new Set(landing?.pages);
    for (const child of children) for (const route of child.pages) pages.add(route);
    if (!children.length && !landing) return null;
    // Keep generated navigation in its own namespace; never overwrite a real page.
    let url = `${base}/_markdown/${key}.md`;
    while (byRoute.has(routeKey(url.slice(0, -3))) || generated.has(url)) url = url.slice(0, -3) + '-index.md';
    const node = { title, children, pages, url: landing?.url || url };
    if (!landing) generated.set(url, node);
    return node;
  }

  const roots = [];
  for (const version of versions) {
    const byId = new Map(version.docs.map((doc) => [doc.id, doc.permalink]));
    function walk(items, key) {
      return items.flatMap((item, index) => {
        // Repeated reference branches are aliases, not additional hierarchy.
        if (item.customProps?.yamlReference || item.customProps?.navigationReference || item.type === 'html') return [];
        if (item.type === 'category') {
          const nodeKey = `${key}/${index}-${slug(item.label)}`;
          const children = walk(item.items || [], nodeKey);
          const route = item.link?.type === 'doc' ? byId.get(item.link.id) : undefined;
          const landing = route ? page(route) : null;
          return category(item.label, children, landing, nodeKey) || [];
        }
        const route = byId.get(item.id) || item.href;
        if (!route) return [];
        const doc = page(route, item.label);
        if (doc) return doc;
        // Keep links to HTML-only pages and external resources usable as well.
        if (item.type === 'link') return { title: item.label, url: item.href, pages: new Set() };
        return [];
      });
    }
    for (const [name, items] of Object.entries(version.sidebars)) {
      const key = `${slug(version.instanceId)}/${slug(version.versionName)}/${slug(name)}`;
      const node = category(navbarLabels.get(name) || items.find((item) => item.customProps?.navigationOverview)?.label || readable(name), walk(items, key), null, key);
      if (node) roots.push(node);
    }
  }

  const rank = (node) => navbarOrder.includes(node.title) ? navbarOrder.indexOf(node.title) : navbarOrder.length;
  roots.sort((a, b) => rank(a) - rank(b));

  // Blog posts and docs omitted from sidebars remain discoverable, without
  // inventing parent/child relationships from their URL paths.
  const remaining = new Map();
  for (const doc of documents) {
    if (visited.has(routeKey(doc.routePath)) || routeKey(doc.routePath) === '/') continue;
    const section = doc.routePath.slice(base.length).split('/').filter(Boolean)[0];
    if (!remaining.has(section)) remaining.set(section, []);
    remaining.get(section).push(doc);
  }
  const extra = [];
  for (const [section, docs] of [...remaining].sort(([a], [b]) => a.localeCompare(b))) {
    const children = docs.map((doc) => page(doc.routePath));
    extra.push(category(readable(section), children, null, `additional/${slug(section)}`));
  }
  if (extra.length) roots.push(category('Additional documentation', extra, null, 'additional'));

  for (const [url, node] of generated) {
    const file = path.join(outDir, url.replace(/^\//, ''));
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, `# ${node.title}\n\n${count(node)}.\n\n${node.children.map((child) => `- ${link(child)}${child.children ? ` — ${count(child)}.` : ''}`).join('\n')}\n\n[Documentation index](<${rootURL}>)\n`);
  }

  // Root overview shows categories at their actual depth. Leaf pages live in
  // the linked section indexes, keeping the overview compact.
  const lines = [];
  function overview(nodes, depth = 0) {
    for (const node of nodes) {
      lines.push(`${'  '.repeat(depth)}- ${link(node)} — ${count(node)}.`);
      if (node.children) overview(node.children.filter((child) => child.children), depth + 1);
    }
  }
  overview(roots);
  return lines;
}

module.exports = { generateNavigationIndexes };
