// Package rds embeds Amazon RDS's global CA certificate trust bundle, used as the default TLS
// trust anchor for `atmos aws rds connect` (see pkg/cacerts.BuildBundle, which combines this
// bundle with the host's system CA store).
//
// Amazon RDS and Aurora endpoints present certificates chained to Amazon's own private root CAs,
// which are never part of a host's public system trust store. Without this bundle, verify-full
// (postgres) / VERIFY_IDENTITY (mysql) TLS verification fails against real RDS endpoints out of
// the box, and on Windows (where there is no canonical file-based system CA bundle at all) no CA
// would be supplied whatsoever.
//
// Provenance:
//   - Source: https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem
//   - Fetched: 2026-07-24
//
// The bundle carries both the current and previous generations of RDS root/intermediate CAs (AWS
// rotates these on a multi-year cycle), so a stale copy degrades gracefully: certificates issued
// under an older root remain verifiable even after this file falls out of date; only endpoints
// re-issued under a newly-rotated root (not yet present here) would fail verification.
//
// This file carries no license/attribution terms from AWS — it is a public trust bundle, not
// licensed software — so it is intentionally excluded from the autogenerated NOTICE file (which
// covers only Go module dependency licenses).
//
