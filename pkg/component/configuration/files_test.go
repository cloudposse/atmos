func TestWriteFilesOwnershipAndLiteralContent(t *testing.T) {
	root := t.TempDir()
	file := schema.ComponentConfigurationFile{Path: "nested/context.tf", Content: []byte(`{{ do not render }} ${terraform.expression}`), IfExists: "error"}
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	path := filepath.Join(root, file.Path)
	content, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, file.Content, content)
	// Writing the same bytes again is not a conflict: the file is the one this host generated.
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	// A different file of the same name that this host did not generate still is.
	require.NoError(t, os.WriteFile(path, []byte("authored by someone else"), 0o600))
	require.ErrorIs(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}), errUtils.ErrPluginInvalidConfig)
	file.Content = []byte("replacement")
	file.IfExists = "skip"
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	content, err = os.ReadFile(path)
	require.NoError(t, err)
	require.NotEqual(t, file.Content, content)
	file.IfExists = "overwrite"
	file.Sensitive = true
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	content, err = os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, file.Content, content)
	stat, err := os.Stat(path)
	require.NoError(t, err)
	if runtime.GOOS != "windows" {
		require.Equal(t, os.FileMode(0o600), stat.Mode().Perm())
	}
	require.NoError(t, WriteFiles("unavailable", nil))
	require.ErrorIs(t, WriteFiles(filepath.Join(root, "absent"), []schema.ComponentConfigurationFile{file}), errUtils.ErrPluginInvalidConfig)
}

func TestWriteFilesPreflightAndContainment(t *testing.T) {
	root := t.TempDir()
	first := schema.ComponentConfigurationFile{Path: "first.tf", Content: []byte("content"), IfExists: "error"}
	for _, file := range []schema.ComponentConfigurationFile{{Path: "../escape.tf", IfExists: "overwrite"}, {Path: "bad.tf", IfExists: "unknown"}} {
		require.Error(t, WriteFiles(root, []schema.ComponentConfigurationFile{first, file}))
		_, err := os.Stat(filepath.Join(root, first.Path))
		require.True(t, os.IsNotExist(err))
	}
	outside := t.TempDir()
	if err := os.Symlink(outside, filepath.Join(root, "link")); err != nil {
		t.Skipf("symlink unavailable: %v", err)
	}
	require.Error(t, WriteFiles(root, []schema.ComponentConfigurationFile{{Path: "link/escape.tf", IfExists: "overwrite"}}))
	_, err := os.Stat(filepath.Join(outside, "escape.tf"))
	require.True(t, os.IsNotExist(err))
}

// A sensitive file that already holds the generated bytes is kept as is, and its content is still
// registered for masking, so a hook that prints it in a later invocation is masked.
func TestWriteFilesRegistersSensitiveContentItKeeps(t *testing.T) {
	t.Cleanup(atmosio.Reset)
	atmosio.Reset()
	require.NoError(t, atmosio.Initialize())
	root := t.TempDir()
	secret := "kept-backend-credential-4b1d"
	file := schema.ComponentConfigurationFile{Path: "backend.tf", Content: []byte(secret), IfExists: "overwrite", Sensitive: true}
	require.NoError(t, os.WriteFile(filepath.Join(root, file.Path), file.Content, 0o600))
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	require.Equal(t, "key=<MASKED>", atmosio.MaskString("key="+secret))
}

func TestSensitiveGeneratedFileRestrictsBeforeTruncating(t *testing.T) {
	directory := t.TempDir()
	path := filepath.Join(directory, "secret.tf")
	previous := []byte("preserve until restricted")
	require.NoError(t, os.WriteFile(path, previous, 0o644))
	root, err := os.OpenRoot(directory)
	require.NoError(t, err)
	defer root.Close()
	output, err := openGeneratedFile(root, schema.ComponentConfigurationFile{
		Path: "secret.tf", IfExists: "overwrite", Sensitive: true,
	}, true)
	require.NoError(t, err)
	defer output.Close()
	info, err := output.Stat()
	require.NoError(t, err)
	require.EqualValues(t, len(previous), info.Size())
	if runtime.GOOS != "windows" {
		require.Equal(t, os.FileMode(secretMode), info.Mode().Perm())
	}
}

func TestSensitiveGeneratedFileExistingPolicies(t *testing.T) {
	for _, policy := range []string{"skip", "error"} {
		t.Run(policy, func(t *testing.T) {
			directory := t.TempDir()
			path := filepath.Join(directory, "secret.tf")
			previous := []byte("preserve existing content")
			require.NoError(t, os.WriteFile(path, previous, 0o644))
			err := WriteFiles(directory, []schema.ComponentConfigurationFile{{
				Path: "secret.tf", IfExists: policy, Sensitive: true, Content: []byte("replacement"),
			}})
			if policy == "skip" {
				require.NoError(t, err)
			} else {
				require.ErrorIs(t, err, errUtils.ErrPluginInvalidConfig)
			}
			content, err := os.ReadFile(path)
			require.NoError(t, err)
			require.Equal(t, previous, content)
		})
	}
}

// A module file that already matches a skip block stays the module's: removing the block later
// must not delete it as a stale generated file.
func TestSkipKeepsOwnershipOfAnIdenticalModuleFile(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "versions.tf")
	content := []byte("terraform {}\n")
	require.NoError(t, os.WriteFile(path, content, 0o644))
	file := schema.ComponentConfigurationFile{Path: "versions.tf", Content: content, IfExists: "skip"}
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	require.NoError(t, WriteFiles(root, nil))
	got, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, content, got)
	// A skip file this host created is still its own and is removed with its block.
	generated := schema.ComponentConfigurationFile{Path: "generated.tf", Content: content, IfExists: "skip"}
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{generated}))
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{generated}))
	require.NoError(t, WriteFiles(root, nil))
	require.NoFileExists(t, filepath.Join(root, generated.Path))
}

func TestEnsureModeWrapsPermissionFailures(t *testing.T) {
	root, err := os.OpenRoot(t.TempDir())
	require.NoError(t, err)
	t.Cleanup(func() { _ = root.Close() })
	err = ensureMode(root, schema.ComponentConfigurationFile{Path: "missing.tf"})
	require.ErrorIs(t, err, errUtils.ErrPluginInvalidConfig)
	require.ErrorIs(t, err, os.ErrNotExist, "the filesystem cause is preserved")
	require.ErrorContains(t, err, "missing.tf")
	// A file that exists is tightened without error.
	require.NoError(t, root.WriteFile("present.tf", nil, 0o644))
	require.NoError(t, ensureMode(root, schema.ComponentConfigurationFile{Path: "present.tf"}))
}

func TestWatchPaths(t *testing.T) {
	root := t.TempDir()
	for _, provider := range []bool{true, false} {
		settings := map[string]any{}
		if provider {
			settings["configuration"] = map[string]any{"provider": "terragrunt"}
		}
		absolute := filepath.Join(root, "module")
		deps := []schema.ComponentDependency{{Path: "root.hcl"}, {Path: absolute}}
		require.Equal(t, provider, WatchPaths(&schema.AtmosConfiguration{BasePathAbsolute: root}, settings, deps))
		require.Equal(t, absolute, deps[1].Path)
		if provider {
			require.Equal(t, filepath.Join(root, "root.hcl"), deps[0].Path)
		} else {
			require.Equal(t, "root.hcl", deps[0].Path)
		}
	}
}

// Under if_exists = "error", a module file that already holds the generated bytes is accepted but
// stays the module's: it is not recorded, and removing the generate block keeps it.
func TestErrorPolicyDoesNotClaimAnIdenticalModuleFile(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "versions.tf")
	content := []byte("terraform {}\n")
	require.NoError(t, os.WriteFile(path, content, 0o644))
	file := schema.ComponentConfigurationFile{Path: "versions.tf", Content: content, IfExists: "error"}
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	written, err := os.OpenRoot(root)
	require.NoError(t, err)
	t.Cleanup(func() { _ = written.Close() })
	require.NotContains(t, readManifest(written), "versions.tf", "an unowned file is not recorded")
	require.NoError(t, WriteFiles(root, nil))
	got, err := os.ReadFile(path)
	require.NoError(t, err)
	require.Equal(t, content, got, "removing the block keeps the module's file")
}
