const (
	fileMode              = 0o644
	secretMode            = 0o600
	directoryMode         = 0o755
	sensitiveTempAttempts = 10
	// Requests carry at most the permission, setuid, setgid, and sticky bits.
	maxRequestedMode = 0o7777
	// Granted modes keep owner rwx and group/other read-execute bits only.
	grantedModeMask = 0o755
	ownerReadWrite  = 0o600
)

// CreateSensitiveTemp creates a private file in directory for data that will be
// renamed into place. The file is restricted before the caller writes to it.
func CreateSensitiveTemp(directory string) (*os.File, string, error) {
	defer perf.Track(nil, "configuration.CreateSensitiveTemp")()
	root, err := os.OpenRoot(directory)
	if err != nil {
		return nil, "", fmt.Errorf("%w: open temporary file directory %s: %w", errUtils.ErrFileOperation, directory, err)
	}
	defer root.Close()
	for range sensitiveTempAttempts {
		name := ".atmos-plan-" + rand.Text()
		file, err := createSensitiveTempFile(root, name)
		if errors.Is(err, os.ErrExist) {
			continue
		}
		if err != nil {
			return nil, "", fmt.Errorf("%w: create temporary file in %s: %w", errUtils.ErrFileOperation, directory, err)
		}
		return file, filepath.Join(directory, name), nil
	}
	return nil, "", fmt.Errorf("%w: create temporary file in %s after %d attempts: %w", errUtils.ErrFileOperation, directory, sensitiveTempAttempts, os.ErrExist)
}

// WriteFiles materializes evaluated bytes under the provisioned module, without templating.
//
// It also keeps a manifest of what it generated. A file generated by an earlier run that the
// current run no longer names is removed, so deleting a generate block stops applying it; a
// file under if_exists = "error" is accepted again when it is the one this host wrote; and the
// adjacent Terraform lock-file copy is rewritten only when the copy beside the unit changed.
func WriteFiles(directory string, files []schema.ComponentConfigurationFile) error {
	defer perf.Track(nil, "configuration.WriteFiles")()

	if len(files) == 0 && !manifestExists(directory) {
		return nil
	}
	root, err := os.OpenRoot(directory)
	if err != nil {
		return fmt.Errorf("%w: %w", errUtils.ErrPluginInvalidConfig, err)
	}
	defer root.Close()
	for _, file := range files {
		if err := validateFile(file); err != nil {
			return err
		}
	}
	previous := readManifest(root)
	current := make(map[string]string, len(files))
	names := make([]string, 0, len(files))
	for _, file := range files {
		// Clean the key, so ./provider.tf and provider.tf name the same recorded file.
		key := filepath.ToSlash(filepath.Clean(file.Path))
		names = append(names, key)
		digest, err := writeFile(root, file, previous[key])
		if err != nil {
			return errors.Join(err, keepRecordsAfterFailure(root, previous, current))
		}
		if digest != "" {
			current[key] = digest
		}
	}
	// Record the manifest even when a stale file cannot be removed, so the files written above stay
	// owned and the stale file is retried; then report the removal failure.
	staleErr := removeStaleFiles(root, previous, names, current)
	return errors.Join(writeManifest(root, current), staleErr)
}

// keepRecordsAfterFailure writes the manifest when a batch stops early: the files this run already
// wrote keep their new digests, and every other file keeps its earlier record, so a retry after the
// conflict is fixed still recognizes them as this host's.
func keepRecordsAfterFailure(root *os.Root, previous, current map[string]string) error {
	for key, digest := range previous {
		if _, written := current[key]; !written {
			current[key] = digest
		}
	}
	return writeManifest(root, current)
}

func validateFile(file schema.ComponentConfigurationFile) error {
	if !filepath.IsLocal(file.Path) || file.Mode > maxRequestedMode {
		return errUtils.ErrPluginProtocol
	}
	if !validFilePolicy(file.IfExists) {
		return errUtils.ErrPluginUnsupportedExtension
	}
	return nil
}

// writeFile applies one file's policy and returns the digest to record, or empty when the host
// does not own the file afterwards (removed, or an existing file that "skip" left alone).
func writeFile(root *os.Root, file schema.ComponentConfigurationFile, recorded string) (string, error) {
	remove, err := checkFileOwnership(root, file, recorded)
	if err != nil {
		return "", generatedFileError(file.Path, err)
	}
	if remove {
		return "", removeGeneratedFile(root, file.Path)
	}
	// Register sensitive bytes even when the file is kept, so a hook that prints it is masked.
	if file.Sensitive {
		atmosio.RegisterSecretValue(string(file.Content))
	}
	digest := contentDigest(file.Content)
	existing, exists := fileDigest(root, file.Path)
	if exists && existing == digest {
		return unchangedFileOutcome(root, file, recorded, digest)
	}
	if exists {
		if keep, owned, err := existingFileOutcome(file, recorded, existing, digest); keep || err != nil {
			return owned, err
		}
	}
	return digest, replaceFile(root, file, exists)
}

// removeGeneratedFile treats an already absent file as successfully removed.
func removeGeneratedFile(root *os.Root, path string) error {
	if err := root.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return generatedFileError(path, err)
	}
	return nil
}

// unchangedFileOutcome retains ownership only when an identical file belongs to this host.
func unchangedFileOutcome(root *os.Root, file schema.ComponentConfigurationFile, recorded, digest string) (string, error) {
	if (file.IfExists == "skip" || file.IfExists == "error") && recorded != digest {
		// A file the module already ships, or any file this host did not write, stays unowned, so
		// removing the block keeps it. Its bytes already match, so if_exists = "error" has nothing to reject.
		return "", nil
	}
	// Already what would be written, so even if_exists = "error" has nothing to protect.
	return digest, ensureMode(root, file)
}

// existingFileOutcome applies the policy to a file that exists with different bytes. It reports
// whether the file is left alone, and the digest to keep recording for it.
func existingFileOutcome(file schema.ComponentConfigurationFile, recorded, existing, digest string) (bool, string, error) {
	switch {
	case keepsUnitLockFile(file, recorded, digest):
		return true, recorded, nil
	case file.IfExists == "skip":
		return true, recordedIfOwned(recorded, existing), nil
	case file.IfExists == "error" && (recorded == "" || recorded != existing):
		return false, "", fmt.Errorf("%w: generated file %s already exists and was not generated by this unit (if_exists = \"error\"); remove it from the working directory or use overwrite_terragrunt", errUtils.ErrPluginInvalidConfig, file.Path)
	}
	return false, "", nil
}

// keepsUnitLockFile leaves a lock file Terraform has updated since the unit's copy was last
// copied. The unit's copy takes over again once it changes.
func keepsUnitLockFile(file schema.ComponentConfigurationFile, recorded, digest string) bool {
	return file.UnitFileCopy && file.Path == lockFileName && file.IfExists == "overwrite" && recorded == digest
}

// recordedIfOwned keeps owning a skipped file only while it is still the bytes this host wrote.
func recordedIfOwned(recorded, existing string) string {
	if recorded == existing {
		return recorded
	}
	return ""
}

// ensureMode applies the file's permission bits to a file written by an earlier run, which may
// predate them. Like a fresh write, it leaves the mode alone unless the file is sensitive or
// requests one. Windows keeps its ACLs, except that sensitive files are re-restricted.
func ensureMode(root *os.Root, file schema.ComponentConfigurationFile) error {
	if !file.Sensitive && file.Mode == 0 {
		return nil
	}
	if err := restrictExistingGeneratedFile(root, file); err != nil {
		return generatedFileError(file.Path, err)
	}
	return nil
}

// replaceFile writes the bytes with the file's clamped permission bits; sensitive files, which can
// embed backend credentials, stay private to the owner.
//
// An existing file is replaced through a temporary file renamed over it, so a failed write leaves
// the previous bytes, and the digest recorded for them, valid for a retry.
func replaceFile(root *os.Root, file schema.ComponentConfigurationFile, exists bool) error {
	if err := root.MkdirAll(filepath.Dir(file.Path), directoryMode); err != nil {
		return generatedFileError(file.Path, err)
	}
	// Sensitive files on Windows need the secured handle to retain their ACL and
	// reject concurrent readers while replacing existing bytes.
	if runtime.GOOS == "windows" && file.Sensitive {
		return replaceSensitiveWindowsFile(root, file, exists)
	}
	if !exists {
		return createFile(root, file.Path, file)
	}
	temporary := filepath.Join(filepath.Dir(file.Path), "."+filepath.Base(file.Path)+"."+rand.Text()+".tmp")
	if err := createFile(root, temporary, file); err != nil {
		return generatedFileError(file.Path, err)
	}
	if err := root.Rename(temporary, file.Path); err != nil {
		_ = root.Remove(temporary)
		return generatedFileError(file.Path, err)
	}
	return nil
}

// replaceSensitiveWindowsFile writes the bytes to a secured temporary file and renames it over
// an existing destination only after the write and close succeed, so a failed write leaves the
// previous file unchanged.
func replaceSensitiveWindowsFile(root *os.Root, file schema.ComponentConfigurationFile, exists bool) error {
	if !exists {
		output, err := openGeneratedFile(root, file, false)
		if err != nil {
			return generatedFileError(file.Path, err)
		}
		if err := writeSensitiveGeneratedFile(output, file); err != nil {
			_ = root.Remove(file.Path)
			return err
		}
		return nil
	}
	temporary := filepath.Join(filepath.Dir(file.Path), "."+filepath.Base(file.Path)+"."+rand.Text()+".tmp")
	output, err := createSensitiveTempFile(root, temporary)
	if err != nil {
		return generatedFileError(file.Path, err)
	}
	if err := writeSensitiveGeneratedFile(output, file); err != nil {
		_ = root.Remove(temporary)
		return err
	}
	if err := root.Rename(temporary, file.Path); err != nil {
		_ = root.Remove(temporary)
		return generatedFileError(file.Path, err)
	}
	return nil
}

// writeSensitiveGeneratedFile retains both operation and close failures on the secured handle.
func writeSensitiveGeneratedFile(output *os.File, file schema.ComponentConfigurationFile) error {
	_, writeErr := output.Write(file.Content)
	if err := errors.Join(writeErr, output.Close()); err != nil {
		return generatedFileError(file.Path, err)
	}
	return nil
}

// createFile writes a new file with the permission bits the file carries and removes it again if
// the write does not complete, so a partial file is never left behind.
func createFile(root *os.Root, path string, file schema.ComponentConfigurationFile) error {
	mode := writtenMode(file)
	output, err := root.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return generatedFileError(path, err)
	}
	// Open applies the process umask, so set the mode explicitly.
	if err := applyMode(output, file, mode); err != nil {
		_ = output.Close()
		_ = root.Remove(path)
		return generatedFileError(path, err)
	}
	_, writeErr := output.Write(file.Content)
	if err := errors.Join(writeErr, output.Close()); err != nil {
		_ = root.Remove(path)
		return generatedFileError(path, err)
	}
	return nil
}

// generatedFileError classifies a filesystem failure on a generated file as invalid configuration.
func generatedFileError(path string, err error) error {
	return fmt.Errorf("%w: generated file %s: %w", errUtils.ErrPluginInvalidConfig, path, err)
}

// applyMode sets the permission bits explicitly because open applies the umask
// and leaves an existing file's mode alone. Windows keeps its ACLs.
func applyMode(output *os.File, file schema.ComponentConfigurationFile, mode os.FileMode) error {
	if (!file.Sensitive && file.Mode == 0) || runtime.GOOS == "windows" {
		return nil
	}
	return output.Chmod(mode)
}

// writtenMode returns the clamped permission bits for a generated file. An absent
// mode keeps the historical defaults. A requested mode keeps owner access (rw)
// and the read and execute bits, and drops everything that widens privilege.
// Sensitive files never grant group or other access.
func writtenMode(file schema.ComponentConfigurationFile) os.FileMode {
	if file.Sensitive {
		return os.FileMode(secretMode | file.Mode&0o100)
	}
	if file.Mode == 0 {
		return fileMode
	}
	return os.FileMode(file.Mode&grantedModeMask | ownerReadWrite)
}

// WatchPaths resolves provider-owned watches against the project
// root without putting checkout-specific absolute paths into stack comparisons.
// Existing YAML dependency path semantics remain unchanged. It reports whether
// the dependencies belong to a provider-discovered component.
func WatchPaths(config *schema.AtmosConfiguration, settings map[string]any, deps []schema.ComponentDependency) bool {
	defer perf.Track(nil, "configuration.WatchPaths")()
	if !schema.ConfigurationOwned(settings) {
		return false
	}
	for i := range deps {
		if !filepath.IsAbs(deps[i].Path) {
			deps[i].Path = filepath.Join(config.BasePathAbsolute, deps[i].Path)
		}
	}
	return true
}
