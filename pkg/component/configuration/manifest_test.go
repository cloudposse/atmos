func generated(path, content, policy string) schema.ComponentConfigurationFile {
	return schema.ComponentConfigurationFile{Path: path, Content: []byte(content), IfExists: policy}
}

func read(t *testing.T, root, path string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, path))
	require.NoError(t, err)
	return string(data)
}

func TestRemovedGenerateBlockStopsBeingApplied(t *testing.T) {
	root := t.TempDir()
	signed := "# Generated by Terragrunt. Sig: nIlQXj57tbuaRZEa\nvariable \"stale_marker\" {}\n"
	unsigned := "variable \"unsigned\" {}\n"
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{
		generated("provider.tf", signed, "overwrite_terragrunt"),
		generated("nested/dir/extra.tf", unsigned, "overwrite"),
		generated("keep.tf", unsigned, "overwrite"),
	}))
	require.FileExists(t, filepath.Join(root, "provider.tf"))

	// The next run generates only keep.tf: both other files were this host's, and both go.
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{generated("keep.tf", unsigned, "overwrite")}))
	require.NoFileExists(t, filepath.Join(root, "provider.tf"))
	require.NoFileExists(t, filepath.Join(root, "nested", "dir", "extra.tf"))
	require.NoDirExists(t, filepath.Join(root, "nested"), "directories left empty are removed with their file")
	require.FileExists(t, filepath.Join(root, "keep.tf"))

	// Generating nothing at all removes the rest and the manifest with it.
	require.NoError(t, WriteFiles(root, nil))
	require.NoFileExists(t, filepath.Join(root, "keep.tf"))
	require.NoFileExists(t, filepath.Join(root, ".atmos", "generated-files.json"))
}

func TestStaleCleanupNeverRemovesFilesTheHostDoesNotOwn(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{
		generated("edited.tf", "generated\n", "overwrite"),
		generated("replaced.tf", "generated\n", "overwrite"),
		generated("gone.tf", "generated\n", "overwrite"),
	}))
	require.NoError(t, os.WriteFile(filepath.Join(root, "edited.tf"), []byte("edited by hand\n"), 0o600))
	require.NoError(t, os.Remove(filepath.Join(root, "replaced.tf")))
	require.NoError(t, os.Mkdir(filepath.Join(root, "replaced.tf"), 0o755), "a directory now has the generated name")
	require.NoError(t, os.WriteFile(filepath.Join(root, "module.tf"), []byte("from the module\n"), 0o600))
	require.NoError(t, os.Remove(filepath.Join(root, "gone.tf")))

	require.NoError(t, WriteFiles(root, nil))

	require.Equal(t, "edited by hand\n", read(t, root, "edited.tf"), "a changed file is no longer the generated one")
	require.DirExists(t, filepath.Join(root, "replaced.tf"))
	require.Equal(t, "from the module\n", read(t, root, "module.tf"))
}

func TestStaleCleanupIgnoresUnsafeManifestPaths(t *testing.T) {
	root := t.TempDir()
	outside := filepath.Join(t.TempDir(), "victim.tf")
	require.NoError(t, os.WriteFile(outside, []byte("x"), 0o600))
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".atmos"), 0o755))
	relative, err := filepath.Rel(root, outside)
	require.NoError(t, err)
	manifest := `{"files":{"` + filepath.ToSlash(relative) + `":"` + contentDigest([]byte("x")) + `"}}`
	require.NoError(t, os.WriteFile(filepath.Join(root, ".atmos", "generated-files.json"), []byte(manifest), 0o600))

	require.NoError(t, WriteFiles(root, nil))
	require.FileExists(t, outside, "a manifest cannot direct removal outside the working directory")
}

func TestErrorPolicyAcceptsOnlyTheFileThisHostGenerated(t *testing.T) {
	root := t.TempDir()
	file := generated("provider.tf", "provider \"x\" {}\n", "error")
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	for range 2 {
		require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}), "a rerun must not fail on its own file")
	}

	// New content for the same path replaces the file this host wrote earlier.
	file.Content = []byte("provider \"y\" {}\n")
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}))
	require.Equal(t, "provider \"y\" {}\n", read(t, root, "provider.tf"))

	// A file the host did not write is a conflict, and the message names the file and the way out.
	other := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(other, "provider.tf"), []byte("authored\n"), 0o600))
	err := WriteFiles(other, []schema.ComponentConfigurationFile{file})
	require.ErrorIs(t, err, errUtils.ErrPluginInvalidConfig)
	require.Contains(t, err.Error(), "provider.tf")
	require.Contains(t, err.Error(), "overwrite_terragrunt")
	require.Equal(t, "authored\n", read(t, other, "provider.tf"))
}

func TestOverwriteTerragruntOwnsUnsignedFilesItWrote(t *testing.T) {
	root := t.TempDir()
	file := generated("secret.auto.tfvars", "token = \"a\"\n", "overwrite_terragrunt")
	require.NoError(t, os.WriteFile(filepath.Join(root, "secret.auto.tfvars"), []byte("authored\n"), 0o600))
	require.ErrorIs(t, WriteFiles(root, []schema.ComponentConfigurationFile{file}), errUtils.ErrPluginInvalidConfig)

	fresh := t.TempDir()
	require.NoError(t, WriteFiles(fresh, []schema.ComponentConfigurationFile{file}))
	file.Content = []byte("token = \"b\"\n")
	require.NoError(t, WriteFiles(fresh, []schema.ComponentConfigurationFile{file}), "an unsigned file the host wrote stays owned")
	require.Equal(t, "token = \"b\"\n", read(t, fresh, "secret.auto.tfvars"))
}

func TestGeneratedFilesArePrivateToTheOwner(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("POSIX permissions")
	}
	root := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(root, "backend.tf"), []byte("old"), 0o644))
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{
		generated("backend.tf", "terraform { backend \"s3\" { secret_key = \"k\" } }\n", "overwrite"),
		generated("provider.tf", "provider {}\n", "overwrite"),
	}))
	for _, name := range []string{"backend.tf", "provider.tf"} {
		info, err := os.Stat(filepath.Join(root, name))
		require.NoError(t, err)
		require.Equal(t, os.FileMode(0o600), info.Mode().Perm(), name)
	}
	// An unchanged file written by an older run with a wider mode is tightened too.
	require.NoError(t, os.Chmod(filepath.Join(root, "provider.tf"), 0o644))
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{
		generated("backend.tf", "terraform { backend \"s3\" { secret_key = \"k\" } }\n", "overwrite"),
		generated("provider.tf", "provider {}\n", "overwrite"),
	}))
	info, err := os.Stat(filepath.Join(root, "provider.tf"))
	require.NoError(t, err)
	require.Equal(t, os.FileMode(0o600), info.Mode().Perm())
}

// Terraform rewrites the lock file during init. The unit's copy must not undo that on every run,
// but must take over again when the copy beside the unit changes.
func TestUnitLockFileIsCopiedOnlyWhenItChanges(t *testing.T) {
	root := t.TempDir()
	lock := func(content string) []schema.ComponentConfigurationFile {
		return []schema.ComponentConfigurationFile{generated(lockFileName, content, "overwrite")}
	}
	require.NoError(t, WriteFiles(root, lock("# pinned v1\n")))
	require.Equal(t, "# pinned v1\n", read(t, root, lockFileName))

	require.NoError(t, os.WriteFile(filepath.Join(root, lockFileName), []byte("# upgraded by init\n"), 0o600))
	require.NoError(t, WriteFiles(root, lock("# pinned v1\n")))
	require.Equal(t, "# upgraded by init\n", read(t, root, lockFileName), "an unchanged unit copy must not overwrite what init wrote")

	require.NoError(t, WriteFiles(root, lock("# pinned v2\n")))
	require.Equal(t, "# pinned v2\n", read(t, root, lockFileName), "an edited unit copy takes over")

	require.NoError(t, os.Remove(filepath.Join(root, lockFileName)))
	require.NoError(t, WriteFiles(root, lock("# pinned v2\n")))
	require.Equal(t, "# pinned v2\n", read(t, root, lockFileName), "a missing lock file is restored")
}

func TestCorruptManifestOnlyCostsCleanup(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, ".atmos"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, ".atmos", "generated-files.json"), []byte("{not json"), 0o600))
	require.NoError(t, WriteFiles(root, []schema.ComponentConfigurationFile{generated("a.tf", "a\n", "overwrite")}))
	require.Equal(t, "a\n", read(t, root, "a.tf"))
	require.Contains(t, read(t, root, ".atmos/generated-files.json"), "a.tf")
}
