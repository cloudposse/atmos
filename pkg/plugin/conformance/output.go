package conformance

import (
	"bytes"
	"context"
	"errors"

	errUtils "github.com/cloudposse/atmos/errors"
	"github.com/cloudposse/atmos/pkg/perf"
)

const maxCapturedOutput = 1 << 20

type capturedOutput struct{ bytes.Buffer }

func (output *capturedOutput) Write(value []byte) (int, error) {
	defer perf.Track(nil, "conformance.capturedOutput.Write")()

	if len(value) > maxCapturedOutput-output.Len() {
		return 0, errUtils.ErrPluginPayloadTooLarge
	}
	return output.Buffer.Write(value)
}

func safeFailure(err error) error {
	if err == nil {
		return nil
	}
	if errors.Is(err, context.Canceled) {
		return errors.Join(errUtils.ErrTestsFailed, context.Canceled)
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return errors.Join(errUtils.ErrTestsFailed, context.DeadlineExceeded)
	}
	// The selection error is generated by Atmos and lists only test names, never plugin output.
	if errors.Is(err, errUtils.ErrPluginTestsNotMatched) {
		return err
	}
	// Plugin RPC errors may contain credentials. Case names and masked, bounded details in the
	// report identify failures.
	return errUtils.ErrTestsFailed
}
