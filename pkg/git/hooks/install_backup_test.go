package hooks

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestInstallBacksUpPreCommitHooksWithForce(t *testing.T) {
	for _, tc := range []struct {
		name, source string
		force        bool
		wantError    bool
	}{
		{"recognized", "#!/bin/sh\n# File generated by pre-commit:\noriginal\n", true, false},
		{"custom without force", "#!/bin/sh\ncustom\n", false, true},
		{"explicit force required", "# File generated by pre-commit:\noriginal\n", false, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			path := filepath.Join(dir, "pre-commit")
			require.NoError(t, os.WriteFile(path, []byte(tc.source), 0o755))
			err := installHook(dir, "pre-commit", tc.force)
			data, readErr := os.ReadFile(path)
			require.NoError(t, readErr)
			backups, globErr := filepath.Glob(path + ".before-atmos-*")
			require.NoError(t, globErr)
			if tc.wantError {
				require.Error(t, err)
				require.Equal(t, tc.source, string(data))
				require.Empty(t, backups)
				return
			}
			require.NoError(t, err)
			require.Contains(t, string(data), ShimMarker)
			require.Len(t, backups, 1)
			original, err := os.ReadFile(backups[0])
			require.NoError(t, err)
			require.Equal(t, tc.source, string(original))
			require.NoError(t, installHook(dir, "pre-commit", true))
			backups, err = filepath.Glob(path + ".before-atmos-*")
			require.NoError(t, err)
			require.Len(t, backups, 1)
		})
	}
}
